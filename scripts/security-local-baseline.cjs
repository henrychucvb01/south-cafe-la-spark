// Reconstruct schema metadata only in the isolated local PostgreSQL cluster.
// No production records, credentials, or network database connections are used.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve('.security-runtime');
const snapshot = JSON.parse(fs.readFileSync(path.join(root, 'schema.json'), 'utf8'));
const extra = JSON.parse(fs.readFileSync(path.join(root, 'additional-metadata.json'), 'utf8'));
const q = value => '"' + value.replaceAll('"', '""') + '"';
const qualified = (schema, name) => `${q(schema)}.${q(name)}`;
const sql = [
  "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN BYPASSRLS; END IF; END $$;",
  'CREATE SCHEMA extensions; CREATE EXTENSION pgcrypto WITH SCHEMA extensions;',
  'CREATE SCHEMA october_dev; CREATE SCHEMA october_live;',
  'SET search_path=public,extensions; SET check_function_bodies=off;',
];
for (const sequence of snapshot.sequences) sql.push(`CREATE SEQUENCE ${qualified(sequence.schema, sequence.name)};`);
for (const table of snapshot.tables) {
  const columns = table.columns.map(c => `${q(c.name)} ${c.type}${c.generated ? ` GENERATED ALWAYS AS (${c.default}) STORED` : c.identity ? ' GENERATED BY DEFAULT AS IDENTITY' : c.default ? ` DEFAULT ${c.default}` : ''}${c.notnull ? ' NOT NULL' : ''}`);
  sql.push(`CREATE TABLE ${qualified(table.schema, table.name)} (${columns.join(',')});`);
}
for (const fn of snapshot.functions) sql.push(fn.definition + ';');
const constraints = [...snapshot.constraints].sort((a,b) => Number(a.definition.startsWith('FOREIGN')) - Number(b.definition.startsWith('FOREIGN')));
for (const c of constraints) sql.push(`ALTER TABLE ${qualified(c.schema,c.table)} ADD CONSTRAINT ${q(c.name)} ${c.definition};`);
const names = new Set(constraints.map(c=>`${c.schema}.${c.name}`));
for (const index of snapshot.indexes) if (!names.has(`${index.schemaname}.${index.indexname}`)) sql.push(index.indexdef+';');
for (const trigger of snapshot.triggers) sql.push(trigger+';');
for (const view of extra.views) sql.push(`CREATE VIEW public.${q(view.name)} AS ${view.definition};`);
for (const table of snapshot.tables) if (table.rls) sql.push(`ALTER TABLE ${qualified(table.schema,table.name)} ENABLE ROW LEVEL SECURITY;`);
for (const p of snapshot.policies) {
  const roles = Array.isArray(p.roles) ? p.roles : p.roles.replace(/[{}]/g,'').split(',');
  sql.push(`CREATE POLICY ${q(p.policyname)} ON ${qualified(p.schemaname,p.tablename)} AS ${p.permissive} FOR ${p.cmd} TO ${roles.map(q).join(',')}${p.qual ? ` USING (${p.qual})` : ''}${p.with_check ? ` WITH CHECK (${p.with_check})` : ''};`);
}
const tableNames = new Set([...snapshot.tables.map(t=>`${t.schema}.${t.name}`),...extra.views.map(v=>`public.${v.name}`)]);
for (const g of snapshot.grants) if (tableNames.has(`${g.table_schema}.${g.table_name}`)) sql.push(`GRANT ${g.privilege_type} ON ${qualified(g.table_schema,g.table_name)} TO ${q(g.grantee)};`);
sql.push('GRANT USAGE ON SCHEMA public TO anon,authenticated,service_role; GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO anon,authenticated,service_role;');
for (const f of snapshot.functions) {
  sql.push(`REVOKE ALL ON FUNCTION ${f.identity} FROM PUBLIC,anon,authenticated;`);
  for (const role of ['anon','authenticated']) if(f[role]) sql.push(`GRANT EXECUTE ON FUNCTION ${f.identity} TO ${role};`);
  if(extra.service_functions.includes(f.identity.replace(/^public\./,''))) sql.push(`GRANT EXECUTE ON FUNCTION ${f.identity} TO service_role;`);
}
fs.writeFileSync(path.join(root,'baseline.sql'),sql.join('\n'));
console.log(`Generated isolated baseline: ${snapshot.tables.length} tables; ${snapshot.functions.length} functions. No school records included.`);
