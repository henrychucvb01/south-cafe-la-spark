create table if not exists public.ar_training_question_keys (
  question_id text primary key,
  correct_index integer not null check (correct_index between 0 and 3),
  approved_source_chunk_id text not null,
  active boolean not null default true
);

create table if not exists public.ar_training_daily_progress (
  location_id bigint not null,
  service_date date not null,
  points_awarded integer not null default 0 check (points_awarded between 0 and 10),
  correct_answers integer not null default 0,
  total_attempts integer not null default 0,
  awarded_question_ids jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now(),
  primary key (location_id, service_date)
);

create table if not exists public.ar_training_attempts (
  id bigint generated by default as identity primary key,
  location_id bigint not null,
  employee_id bigint null,
  employee_name text null,
  service_date date not null,
  question_id text not null references public.ar_training_question_keys(question_id),
  selected_index integer not null check (selected_index between 0 and 3),
  is_correct boolean not null,
  points_awarded integer not null default 0 check (points_awarded in (0, 2)),
  answered_at timestamptz not null default now()
);

create index if not exists ar_training_attempts_location_date_idx
  on public.ar_training_attempts (location_id, service_date desc);

alter table public.ar_training_question_keys enable row level security;
alter table public.ar_training_daily_progress enable row level security;
alter table public.ar_training_attempts enable row level security;

revoke all on public.ar_training_question_keys from anon, authenticated;
grant select on public.ar_training_daily_progress to anon, authenticated;
revoke insert, update, delete on public.ar_training_daily_progress from anon, authenticated;
revoke all on public.ar_training_attempts from anon, authenticated;

drop policy if exists "AR progress is readable" on public.ar_training_daily_progress;
create policy "AR progress is readable"
  on public.ar_training_daily_progress for select
  to anon, authenticated
  using (true);

