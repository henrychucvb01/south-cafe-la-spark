-- Shared manager/supervisor area location directory.
create table if not exists public.location_information (
  id bigint generated by default as identity primary key,
  location_code text unique,
  school_name text not null,
  manager_name text,
  site_type text,
  counting_claiming text,
  cafeteria_phone text,
  school_phone text,
  supervisor_name text,
  supervisor_email text,
  supervisor_cell text,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create index if not exists location_information_school_name_idx
  on public.location_information (school_name);

alter table public.location_information enable row level security;

drop policy if exists "location information is readable" on public.location_information;
create policy "location information is readable"
  on public.location_information for select
  to anon, authenticated
  using (active = true);

revoke insert, update, delete on public.location_information from anon, authenticated;
grant select on public.location_information to anon, authenticated;

