create or replace function public.update_location_information(
  p_supervisor_pin text,
  p_id bigint,
  p_location_code text,
  p_school_name text,
  p_manager_name text,
  p_site_type text,
  p_counting_claiming text,
  p_cafeteria_phone text,
  p_school_phone text,
  p_supervisor_name text,
  p_supervisor_email text,
  p_supervisor_cell text
) returns public.location_information
language plpgsql
security definer
set search_path = public
as $$
declare
  v_record public.location_information;
begin
  if public.verify_supervisor_pin(p_supervisor_pin) is not true then
    raise exception 'Supervisor authorization failed';
  end if;

  if nullif(trim(p_school_name), '') is null then
    raise exception 'School name is required';
  end if;

  update public.location_information
  set location_code = nullif(trim(p_location_code), ''),
      school_name = trim(p_school_name),
      manager_name = nullif(trim(p_manager_name), ''),
      site_type = nullif(trim(p_site_type), ''),
      counting_claiming = nullif(trim(p_counting_claiming), ''),
      cafeteria_phone = nullif(trim(p_cafeteria_phone), ''),
      school_phone = nullif(trim(p_school_phone), ''),
      supervisor_name = nullif(trim(p_supervisor_name), ''),
      supervisor_email = nullif(trim(p_supervisor_email), ''),
      supervisor_cell = nullif(trim(p_supervisor_cell), ''),
      updated_at = now()
  where id = p_id
  returning * into v_record;

  if v_record.id is null then
    raise exception 'Location record not found';
  end if;

  return v_record;
end;
$$;

revoke all on function public.update_location_information(text, bigint, text, text, text, text, text, text, text, text, text, text) from public;
grant execute on function public.update_location_information(text, bigint, text, text, text, text, text, text, text, text, text, text) to anon, authenticated;
